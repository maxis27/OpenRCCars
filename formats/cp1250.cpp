uint32_t toUnicode(uint8_t c) {
  return c<0x80 ? c : High[c-0x80];
  }

int fromUnicode(uint32_t u) {
  if(u<0x80)
    return int(u);
  for(int i=0; i<128; ++i)
    if(High[i]==u && u!=0)
      return 0x80+i;
  return -1;
  }

std::string toUtf8(std::string_view s) {
  std::string r;
  r.reserve(s.size());
  for(char ch:s) {
    const uint32_t u = toUnicode(uint8_t(ch));
    if(u==0 && ch!=0)
      continue;
    if(u<0x80) {
      r.push_back(char(u));
      }
    else if(u<0x800) {
      r.push_back(char(0xc0|(u>>6)));
      r.push_back(char(0x80|(u&0x3f)));
      }
    else {
      r.push_back(char(0xe0|(u>>12)));
      r.push_back(char(0x80|((u>>6)&0x3f)));
      r.push_back(char(0x80|(u&0x3f)));
      }
    }
  return r;
  }

std::string fromUtf8(std::string_view s) {
  std::string r;
  r.reserve(s.size());
  size_t i = 0;
  while(i<s.size()) {
    const uint8_t c = uint8_t(s[i]);
    uint32_t u    = c;
    size_t   more = 0;
    if(c>=0xf0)      { u = c&0x07; more = 3; }
    else if(c>=0xe0) { u = c&0x0f; more = 2; }
    else if(c>=0xc0) { u = c&0x1f; more = 1; }
    else if(c>=0x80) { r.push_back('?'); ++i; continue; }
    ++i;
    bool ok = true;
    for(size_t k=0; k<more; ++k, ++i) {
      if(i>=s.size() || (uint8_t(s[i])&0xc0)!=0x80) {
        ok = false;
        break;
        }
      u = (u<<6)|(uint8_t(s[i])&0x3f);
      }
    const int b = ok ? fromUnicode(u) : -1;
    r.push_back(b>=0 ? char(b) : '?');
    }
  return r;
  }

